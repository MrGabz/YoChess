function evaluateBoard(chess) {
  if (chess.isCheckmate()) return chess.turn() === 'w' ? -99999 : 99999;
  if (chess.isDraw()) return 0;
  let score = 0;
  const board = chess.board();
  for (let rank = 0; rank < 8; rank++) {
    for (let file = 0; file < 8; file++) {
      const piece = board[rank][file];
      if (!piece) continue;
      const idx = rank * 8 + file;
      const flippedIdx = (7 - rank) * 8 + file;
      const pst = PST[piece.type] || [];
      const pstVal = piece.color === 'w' ? (pst[flippedIdx] || 0) : (pst[idx] || 0);
      const val = PIECE_VALUES[piece.type] + pstVal;
      score += piece.color === 'w' ? val : -val;
    }
  }
  return score;
}

function minimax(chess, depth, alpha, beta, maximizing) {
  if (depth === 0 || chess.isGameOver()) return evaluateBoard(chess);
  const moves = chess.moves();
  if (maximizing) {
    let best = -Infinity;
    for (const move of moves) {
      chess.move(move);
      best = Math.max(best, minimax(chess, depth - 1, alpha, beta, false));
      chess.undo();
      alpha = Math.max(alpha, best);
      if (beta <= alpha) break;
    }
    return best;
  } else {
    let best = Infinity;
    for (const move of moves) {
      chess.move(move);
      best = Math.min(best, minimax(chess, depth - 1, alpha, beta, true));
      chess.undo();
      beta = Math.min(beta, best);
      if (beta <= alpha) break;
    }
    return best;
  }
}

function getBestMove(fen, depth, randomness, blunderChance) {
  const chess = new Chess(fen);
  const moves = chess.moves();
  if (moves.length === 0) return null;

  if (Math.random() < blunderChance) return moves[Math.floor(Math.random() * moves.length)];
  if (Math.random() < randomness) return moves[Math.floor(Math.random() * moves.length)];

  const isMaximizing = chess.turn() === 'w';
  let bestMove = null;
  let bestVal = isMaximizing ? -Infinity : Infinity;

  for (const move of moves) {
    chess.move(move);
    const val = minimax(chess, depth - 1, -Infinity, Infinity, !isMaximizing);
    chess.undo();
    if (isMaximizing ? val > bestVal : val < bestVal) {
      bestVal = val;
      bestMove = move;
    }
  }
  return bestMove || moves[0];
}

// Listen for work from the main thread
self.onmessage = function(e) {
  const { id, fen, depth, randomness, blunderChance } = e.data;
  const move = getBestMove(fen, depth, randomness, blunderChance);
  self.postMessage({ id, move });
};
